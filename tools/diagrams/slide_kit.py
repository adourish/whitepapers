#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Building blocks for a slide-sized generated diagram, with the checks built in.

diagram_style.py holds the palette and fonts. This adds what a slide-sized picture needs on top:
zones, cards that measure their own text, arrows with a numbered or lettered step marker, a key
row, and the checks every picture must pass before it is saved.

    from slide_kit import Slide
    s = Slide(3200, 1800, "Title", "One-line subtitle")
    s.zone(30, 160, 900, 1400, "Today", tint="before")
    a = s.card(60, 230, 500, 170, "Consumer app", ["Calls DRMS through its client"])
    b = s.card(60, 470, 500, 170, "DRMS client", ["Old version"], kind="new")
    s.route([(310, a[3]), (310, b[1])], "1", "asks for a token")
    s.key([("step", "1", "A step, in order"), ("dash", None, "Dashed: an event")])
    s.footer("Generated by tools/.../build_example.py from data/x.csv - do not hand-edit.")
    s.save("assets/example.png")          # refuses to save if a check fails

Call s.footer() BEFORE s.key(): the footer takes a band along the bottom edge and the key then sits
just above it. save() refuses a picture whose key reaches into the footer.

Kinds of card: "svc" (white), "new" (cyan - what changes), "store" (square corners - stored data),
"wait" (yellow - waiting or today), "rule" (magenta - a rule that must hold), "open" (dashed border -
not decided yet). Every kind is told apart by shape or border as well as colour.
"""
from __future__ import annotations

import math
import os
import sys

from PIL import Image, ImageDraw

from diagram_style import (INK, GREY, HAIR, PAPER, PANEL, SVC_F, SVC_E, STORE_F, STORE_E, font,
                           footer as _footer, footer_height,
                           TOUCH_F, TOUCH_E, BOTTLE_F, BOTTLE_E, STORY_F, STORY_E)

KINDS = {"svc": (SVC_F, SVC_E), "new": (TOUCH_F, TOUCH_E), "store": (STORE_F, STORE_E),
         "wait": (BOTTLE_F, BOTTLE_E), "rule": (STORY_F, STORY_E), "open": (PAPER, GREY)}
TINTS = {"plain": "#F4F6F8", "new": "#EEF7F9", "before": "#FBF8E8", "outside": "#F6F0FA"}
STEP_F = TOUCH_E          # numbered circle: a runtime step
SETUP_F = STORY_E         # lettered square: a setup or workstream step


class Slide:
    def __init__(self, w, h, title, subtitle=None, sizes=None):
        self.W, self.H = w, h
        self.img = Image.new("RGB", (w, h), PAPER)
        self.d = ImageDraw.Draw(self.img)
        sz = {"title": 50, "sub": 26, "zone": 28, "head": 24, "body": 20, "edge": 19}
        sz.update(sizes or {})
        self.F_TITLE, self.F_SUB = font(sz["title"], True), font(sz["sub"])
        self.F_ZONE, self.F_HEAD = font(sz["zone"], True), font(sz["head"], True)
        self.F_BODY, self.F_EDGE = font(sz["body"]), font(sz["edge"], True)
        self.boxes, self.problems, self.steps = [], [], []
        self.foot_h = 0                     # the band along the bottom edge taken by the footer
        self.key_box = None                 # (x1, y1, x2, y2) of the key panel once drawn
        self.foot_top = None                # y of the top of the footer once drawn
        self._check_width(title, self.F_TITLE, w - 80, "title")
        self.d.text((40, 30), title, fill=INK, font=self.F_TITLE)
        if subtitle:
            self._check_width(subtitle, self.F_SUB, w - 80, "subtitle")
            self.d.text((40, 96), subtitle, fill=GREY, font=self.F_SUB)

    # ---------------------------------------------------------------- checks
    def _check_width(self, text, fnt, width, where):
        if self.d.textlength(text, font=fnt) > width:
            self.problems.append(f"text too wide in {where}: {text!r}")

    def _on_canvas(self, name, x1, y1, x2, y2):
        if x1 < 0 or y1 < 0 or x2 > self.W or y2 > self.H:
            self.problems.append(f"{name!r} runs off the canvas")

    # ---------------------------------------------------------------- shapes
    def zone(self, x, y, w, h, title, tint="plain"):
        self.d.rounded_rectangle([x, y, x + w, y + h], 14, fill=TINTS[tint], outline=HAIR, width=3)
        self.d.text((x + 22, y + 16), title, fill=INK, font=self.F_ZONE)
        self._on_canvas(title, x, y, x + w, y + h)

    def card(self, x, y, w, h, title, lines=(), kind="svc", mark=None):
        """A box that measures its own text. Returns (x1, y1, x2, y2)."""
        fill, edge = KINDS[kind]
        if kind == "store":
            self.d.rectangle([x, y, x + w, y + h], fill=fill, outline=edge, width=3)
        elif kind == "open":
            self.d.rounded_rectangle([x, y, x + w, y + h], 10, fill=fill)
            self._dashed_rect(x, y, x + w, y + h, edge)
        else:
            self.d.rounded_rectangle([x, y, x + w, y + h], 10, fill=fill, outline=edge, width=3)
        pad, ty = 16, y + 16
        reserve = 50 if mark else 0
        self._check_width(title, self.F_HEAD, w - 2 * pad - reserve, title)
        self.d.text((x + pad, ty), title, fill=edge if kind in ("rule", "wait") else INK, font=self.F_HEAD)
        ty += self.F_HEAD.size + 10
        for ln in lines:
            self._check_width(ln, self.F_BODY, w - 2 * pad, title)
            self.d.text((x + pad, ty), ln, fill=INK, font=self.F_BODY)
            ty += self.F_BODY.size + 8
        if ty - 8 + pad > y + h:
            self.problems.append(f"text runs past the bottom of {title!r}")
        if mark:
            self.marker(x + w - 32, y + 32, mark)
        self.boxes.append((title, (x, y, x + w, y + h)))
        self._on_canvas(title, x, y, x + w, y + h)
        return (x, y, x + w, y + h)

    def text(self, x, y, text, bold=False, anchor="la", colour=INK):
        fnt = self.F_EDGE if bold else self.F_BODY
        self.d.text((x, y), text, fill=colour, font=fnt, anchor=anchor)

    def _dashed_rect(self, x1, y1, x2, y2, colour):
        for a, b in (((x1, y1), (x2, y1)), ((x2, y1), (x2, y2)), ((x2, y2), (x1, y2)), ((x1, y2), (x1, y1))):
            self._seg(a, b, colour, 3, True)

    def _seg(self, p1, p2, colour, width, dash):
        if not dash:
            self.d.line([p1, p2], fill=colour, width=width)
            return
        (x1, y1), (x2, y2) = p1, p2
        n = max(2, int(math.hypot(x2 - x1, y2 - y1) / 14))
        for i in range(0, n, 2):
            self.d.line([(x1 + (x2 - x1) * i / n, y1 + (y2 - y1) * i / n),
                         (x1 + (x2 - x1) * (i + 1) / n, y1 + (y2 - y1) * (i + 1) / n)],
                        fill=colour, width=width)

    def marker(self, cx, cy, mark):
        """A numbered circle is a runtime step; a lettered square is a setup step or workstream.
        Shape, not colour, tells them apart."""
        r = 19
        if str(mark).isdigit():
            self.d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=STEP_F)
        else:
            self.d.rectangle([cx - r, cy - r, cx + r, cy + r], fill=SETUP_F)
        self.d.text((cx, cy), str(mark), fill="#FFFFFF", font=self.F_EDGE, anchor="mm")

    def route(self, points, mark=None, label=None, dash=False, colour=GREY, label_at=None, side="right"):
        """An arrow along points. The step marker sits on the first segment; numbers are recorded so
        the save step can check they run 1, 2, 3 without gaps or repeats."""
        last = math.hypot(points[-1][0] - points[-2][0], points[-1][1] - points[-2][1])
        if last < 30:
            self.problems.append(f"arrow {mark or label!r}: last segment shorter than its head")
        for a, b in zip(points, points[1:]):
            self._seg(a, b, colour, 4, dash)
        (x1, y1), (x2, y2) = points[-2], points[-1]
        ang = math.atan2(y2 - y1, x2 - x1)
        self.d.polygon([(x2, y2)] + [(x2 - 20 * math.cos(ang + s), y2 - 20 * math.sin(ang + s))
                                     for s in (-0.42, 0.42)], fill=colour)
        (ax, ay), (bx, by) = points[0], points[1]
        mx, my = (ax + bx) / 2, (ay + by) / 2
        if mark is not None:
            self.marker(mx, my, mark)
            if str(mark).isdigit():
                self.steps.append(int(mark))
        if label:
            lx, ly = label_at or ((mx + 28, my) if side == "right" else (mx - 28, my))
            self.d.text((lx, ly), label, fill=INK, font=self.F_EDGE,
                        anchor={"right": "lm", "left": "rm", "above": "ms", "below": "mt"}[side])

    def key(self, items, y=None):
        """A key row along the bottom. items: (kind, mark, text) with kind in
        step | setup | dash | solid | store | new | wait | rule | open."""
        bottom = self.H - 20 - self.foot_h
        y = y or bottom - 70
        bottom = max(bottom, y + 40)
        self.key_box = (30, y - 30, self.W - 30, bottom)
        self.d.rounded_rectangle(list(self.key_box), 10, fill=PANEL, outline=HAIR, width=2)
        x, col = 60, (self.W - 120) // max(1, len(items))
        for kind, mark, text in items:
            cy = y + 5
            if kind in ("step", "setup"):
                self.marker(x + 20, cy, mark)
            elif kind in ("dash", "solid"):
                self._seg((x, cy), (x + 50, cy), GREY, 4, kind == "dash")
            else:
                fill, edge = KINDS[kind]
                if kind == "store":
                    self.d.rectangle([x, cy - 18, x + 40, cy + 18], fill=fill, outline=edge, width=3)
                elif kind == "open":
                    self._dashed_rect(x, cy - 18, x + 40, cy + 18, edge)
                else:
                    self.d.rounded_rectangle([x, cy - 18, x + 40, cy + 18], 6, fill=fill, outline=edge, width=3)
            self._check_width(text, self.F_BODY, col - 80, "key")
            self.d.text((x + 64, cy), text, fill=INK, font=self.F_BODY, anchor="lm")
            x += col

    def footer(self, text):
        """The provenance line along the bottom edge: which script drew this, from which inputs, and
        that the picture is not to be edited by hand. Checked against the key at save time."""
        self.foot_top = _footer(self.d, self.W, self.H, text)
        self.foot_h = self.H - self.foot_top
        if "do not hand-edit" not in text and "do not edit" not in text:
            self.problems.append("the footer must say the picture is not to be edited by hand")

    # ---------------------------------------------------------------- save
    def save(self, path):
        if self.foot_top is not None and self.key_box and self.key_box[3] > self.foot_top - 4:
            self.problems.append(f"the key (bottom {self.key_box[3]}) overlaps the footer (top {self.foot_top})")
        for i, (na, a) in enumerate(self.boxes):
            for nb, b in self.boxes[i + 1:]:
                if a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]:
                    self.problems.append(f"{na!r} overlaps {nb!r}")
        if self.steps and sorted(self.steps) != list(range(1, len(self.steps) + 1)):
            self.problems.append(f"step numbers are not 1..n without gaps or repeats: {sorted(self.steps)}")
        if self.problems:
            print("NOT WRITTEN - the picture has defects:\n  " + "\n  ".join(self.problems), file=sys.stderr)
            sys.exit(1)
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        self.img.save(path)
        print(f"Wrote {path}")
