#!/usr/bin/env python3
"""Draws the connection pool problem and its fix, side by side, for the pizza shop lab.

The figures come from the lab's own results (../results/results.json, written by ../lab/run_lab.py),
never typed in. Run the lab first, then:
    python papers/connection-pool-lockup-lab/assets/build_pool_problem.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..", "tools", "diagrams")))
from slide_kit import Slide  # noqa: E402

RESULTS = os.path.join(HERE, "..", "results", "results.json")
OUT = os.path.join(HERE, "pool-problem-and-fix.png")
SIZES = {"title": 50, "sub": 28, "zone": 32, "head": 30, "body": 27, "edge": 26}
SAME = ("seconds", "ok", "lost", "retries", "gave_up")


def load():
    """Returns (scenarios from the Java 17 run, a line saying whether every Java gave the same result)."""
    res = json.load(open(RESULTS, encoding="utf-8"))
    runs = res["runs"]
    base = runs["java-17"]["scenarios"]
    same = all(runs[n]["scenarios"][k][f] == base[k][f] for n in runs for k in ("3", "5") for f in SAME)
    javas = ", ".join(f"Java {r['java'].split('.')[0]}{' virtual threads' if r['threads'] == 'virtual' else ''}"
                      for r in runs.values())
    return base, (f"Same result on {javas}." if same else f"Results differ between {javas}: see RESULTS.md.")


def main():
    r, same_line = load()
    need = ["seconds", "pool", "waiting", "ok", "failed", "retries", "gave_up", "staff", "lost"]
    missing = [f"scenario {n}: {k}" for n in ("2", "3", "5") for k in need if k not in r.get(n, {})]
    if missing:
        print("NOT WRITTEN - the lab results are missing:\n  " + "\n  ".join(missing), file=sys.stderr)
        sys.exit(1)
    first, bad, fixed = r["2"], r["3"], r["5"]
    pool, users = bad["pool"], bad["staff"]

    s = Slide(3200, 1620,
              "One order request needs two database connections, so the pool locks up",
              f"Lab: {pool} connections, {users} staff resending pizza ready times at the same moment.  "
              f"Left: the problem.  Right: the fix.  {same_line}",
              sizes=SIZES)
    s.footer("Generated by papers/connection-pool-lockup-lab/assets/build_pool_problem.py from "
             "results/results.json - do not hand-edit.  Made-up data.")

    sides = [
        dict(x=30, title="The problem: each request takes a second connection", tint="before", kind="wait",
             lines=["Holds connection 1 (the transaction)",
                    "Asks for connection 2: none free",
                    "Waits, gives up, loses the history snapshot"],
             extra=("open", f"Request {users}",
                    ["Can't get even one connection",
                     f"Fails; the till tries again ({bad['retries']} retries)",
                     "Each try adds more load"]),
             result=("rule", "Result: the pool is stuck",
                     [f"{bad['waiting']} requests waiting, {bad['lost']} history snapshots lost, "
                      f"{bad['gave_up']} of {users} gave up",
                      f"Took {bad['seconds']:.1f} s, against {first['seconds']:.1f} s for a first send"])),
        dict(x=1630, title="After the fix: one connection per request", tint="new", kind="new",
             lines=["Holds connection 1 (the transaction)",
                    "Saves the snapshot on the same one",
                    "Finishes, gives the connection back"],
             extra=("svc", f"Request {users}",
                    ["Waits a moment for a free one",
                     "Gets it when another request ends",
                     f"Till retries: {fixed['retries']}"]),
             result=("svc", "Result: every request finishes",
                     [f"{fixed['ok']} of {users} finished in {fixed['seconds']:.1f} s",
                      f"History snapshots lost: {fixed['lost']}"])),
    ]

    for side in sides:
        x = side["x"]
        s.zone(x, 160, 1540, 1250, side["title"], tint=side["tint"])
        till = s.card(x + 30, 230, 1480, 110, f"The till: {users} staff press send together",
                       ["Each sends every pizza on its order to the order service in one call"])
        s.route([(x + 770, till[3]), (x + 770, 440)], label="set pizza ready times", side="right")
        s.zone(x + 30, 450, 1480, 700, f"Order service database connection pool: {pool} connections", tint="plain")
        slots = [(x + 60 + col * 720, 520 + row * 210) for row in range(3) for col in range(2)]
        for i, (cx, cy) in enumerate(slots[:pool]):
            s.card(cx, cy, 700, 190, f"Request {i + 1}", side["lines"], kind=side["kind"])
        kind, title, lines = side["extra"]
        ex, ey = slots[pool] if pool < len(slots) else slots[-1]
        s.card(ex, ey, 700, 190, title, lines, kind=kind)
        kind, title, lines = side["result"]
        s.card(x + 30, 1190, 1480, 190, title, lines, kind=kind)

    s.key([("wait", None, "Yellow: waiting for a connection"),
           ("open", None, "Dashed: never got a connection"),
           ("rule", None, "Magenta: what breaks"),
           ("new", None, "Cyan: the fix")])
    s.save(OUT)
    print(f"{pool} connections, {users} users; problem {bad['seconds']:.1f} s, fixed {fixed['seconds']:.1f} s")


if __name__ == "__main__":
    main()
